def call(app, method, path, query=None, headers=None, body=b""):
    return app.handle(method, path, query or {}, headers or {}, body)


def jbody(body):
    return json.loads(body.decode("utf-8"))


def text(body):
    return body.decode("utf-8")


# --------------------------------------------------------------- fake SMTP

class FakeSMTP:
    """Stand-in for ``smtplib.SMTP``: records everything, sends nothing."""

    instances = []

    def __init__(self, host, port, timeout=None, context=None):
        self.host = host
        self.port = port
        self.timeout = timeout
        self.context = context
        self.sent = []
        self.ehlo_calls = 0
        self.started_tls = False
        self.logged_in = None
        self.quit_called = False
        FakeSMTP.instances.append(self)

    def ehlo(self):
        self.ehlo_calls += 1

    def starttls(self, context=None):
        self.started_tls = True

    def login(self, user, password):
        self.logged_in = (user, password)

    def send_message(self, msg, from_addr=None, to_addrs=None):
        self.sent.append({"subject": msg["Subject"], "from": from_addr,
                          "to": list(to_addrs or []),
                          "body": msg.get_content()})

    def quit(self):
        self.quit_called = True

    def close(self):
        pass


class BrokenSMTP:
    """An SMTP host that refuses everything — mail must never propagate."""

    def __init__(self, *args, **kwargs):
        raise OSError("connection refused")


