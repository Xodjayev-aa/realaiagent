class TestOwnerEmail(unittest.TestCase):
    def setUp(self):
        self.agent = make_agent()
        FakeSMTP.instances = []

    def notifier(self, **kwargs):
        options = {"host": "smtp.test", "port": 587, "user": "me@test",
                   "password": "app-password", "sender": "me@test",
                   "recipients": "owner@test, backup@test",
                   "mode": "starttls", "storage": self.agent.storage}
        options.update(kwargs)
        return EmailNotifier(**options)

    def test_disabled_notifier_is_a_noop(self):
        off = EmailNotifier(storage=self.agent.storage)
        self.assertFalse(off.enabled)
        self.assertFalse(off.send("hi", "body"))
        status = off.status()
        self.assertFalse(status["enabled"])
        self.assertIn("REALAI_SMTP_HOST", status["missing"])
        self.assertEqual(FakeSMTP.instances, [])
        # recipients are parsed from any reasonable separator
        self.assertEqual(parse_recipients("a@x.com, b@y.com;c@z.com d@w.com"),
                         ["a@x.com", "b@y.com", "c@z.com", "d@w.com"])
        self.assertEqual(parse_recipients("not-an-address"), [])
        self.assertEqual(parse_recipients(None), [])

    def test_starttls_delivery_and_login(self):
        notifier = self.notifier()
        self.assertTrue(notifier.enabled)
        with mock.patch.object(smtplib, "SMTP", FakeSMTP):
            self.assertTrue(notifier.send("subject", "hello body"))
        client = FakeSMTP.instances[0]
        self.assertEqual((client.host, client.port), ("smtp.test", 587))
        self.assertTrue(client.started_tls)
        self.assertEqual(client.logged_in,
                         ("me@test", "app-password"))
        self.assertTrue(client.quit_called)
        mail = client.sent[0]
        self.assertEqual(mail["subject"], "subject")
        self.assertEqual(mail["from"], "me@test")
        self.assertEqual(mail["to"], ["owner@test", "backup@test"])
        self.assertIn("hello body", mail["body"])
        counters = self.agent.storage.get_counters()["email"]
        self.assertEqual(counters["sent"], 1)
        # an unknown TLS mode falls back to the safe one
        self.assertEqual(self.notifier(mode="wat").mode, "starttls")

    def test_delivery_failure_never_raises(self):
        notifier = self.notifier(host="smtp.broken")
        with mock.patch.object(smtplib, "SMTP", BrokenSMTP):
            self.assertFalse(notifier.send("subject", "body"))
        counters = self.agent.storage.get_counters()["email"]
        self.assertEqual(counters["send_failed"], 1)
        self.assertNotIn("sent", counters)

    def test_cooldown_dedups_repeats(self):
        notifier = self.notifier()
        with mock.patch.object(smtplib, "SMTP", FakeSMTP):
            self.assertTrue(notifier.notify_access_request(
                "mira", note="hi", agent_name="REAL"))
            # the same request twice in a row must not spam the owner
            self.assertFalse(notifier.notify_access_request("mira"))
            self.assertTrue(notifier.notify_access_request("bob"))
        self.assertEqual(len(FakeSMTP.instances), 2)
        first = FakeSMTP.instances[0].sent[0]
        self.assertIn("mira", first["subject"])
        self.assertIn("PENDING", first["body"])
        self.assertIn("/approve", first["body"])
        counters = self.agent.storage.get_counters()["email"]
        self.assertEqual(counters["sent"], 2)
        self.assertEqual(counters["skipped_cooldown"], 1)
        # the password is never part of the diagnostic status
        self.assertNotIn("app-password", json.dumps(notifier.status()))


