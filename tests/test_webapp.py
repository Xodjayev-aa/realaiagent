"""The product layer: branded chat app, conversational voice, owner approvals.

Covers what turned "an API with a demo page" into a product, while the brain
stays 100% local (no external AI, no external API keys):

- ``/``            the branded chat app (logo, favicon, session sidebar,
                   markdown, streaming reveal, typing state, mobile layout)
- ``/developers``  the portal: a live endpoint table from ``/api.json`` plus
                   the key-request form
- ``/approve``     the owner's approval inbox, web-token gated
- conversation     multi-turn context, memory recall, honest scope
- email            stdlib SMTP so key requests reach the owner twice over
- parity           the threaded server serves the same surface as serverless
- serve            ``REALAI_*`` environment variables are honoured

Nothing here touches the network: SMTP is a fake object, HTTP is either
``WebApp.handle`` directly or a server bound to 127.0.0.1.
"""

