    def test_approve_mints_a_key_shown_once(self):
        FakeSMTP.instances = []
        notifier = EmailNotifier(host="smtp.test", port=587, user="me@test",
                                 password="pw", sender="me@test",
                                 recipients="owner@test",
                                 storage=self.agent.storage)
        self.agent.users.mailer = notifier
        with mock.patch.object(smtplib, "SMTP", FakeSMTP):
            status, _c, body, _x = self.post({"action": "approve",
                                              "username": "mira"})
        self.assertEqual(status, 200)
        out = jbody(body)
        self.assertTrue(out["api_key"].startswith("rxa_"))
        self.assertTrue(out["key_id"])
        self.assertEqual(sorted(out["key_scopes"]),
                         ["chat", "devices", "learn"])
        self.assertEqual(out["status"], "APPROVED")
        self.assertEqual(self.agent.storage.user_get("mira")["status"],
                         "APPROVED")

        # a new client starts billed with a zero balance, so the owner's
        # next tap matters: without VIP (or a top-up) the key gets 402
        status, _c, body, _x = call(
            self.app, "GET", "/v1/status", {},
            {"authorization": f"Bearer {out['api_key']}"})
        self.assertEqual(status, 402)
        self.post({"action": "vip", "username": "mira", "vip": True})
        # now the minted key really works, and the inbox never re-renders it
        status, _c, body, _x = call(
            self.app, "GET", "/v1/status", {},
            {"authorization": f"Bearer {out['api_key']}"})
        self.assertEqual(status, 200)
        page = text(call(self.app, "GET", "/approve", {}, self.good)[2])
        self.assertNotIn(out["api_key"], page)
        # ...and a plaintext secret is never emailed to anyone
        for instance in FakeSMTP.instances:
            for mail in instance.sent:
                self.assertNotIn("rxa_", mail["body"])

    def test_deny_bans_and_unban_restores(self):
        status, _c, body, _x = self.post({"action": "approve",
                                          "username": "mira"})
        key = jbody(body)["api_key"]
        status, _c, body, _x = self.post({"action": "deny", "username": "mira"})
        self.assertEqual(status, 200)
        self.assertEqual(jbody(body)["status"], "BANNED")
        self.assertEqual(self.agent.storage.user_get("mira")["status"], "BANNED")
        # their key was revoked with them
        status, _c, _b, _x = call(self.app, "GET", "/v1/status", {},
                                  {"authorization": f"Bearer {key}"})
        self.assertEqual(status, 401)

        status, _c, body, _x = self.post({"action": "unban", "username": "mira"})
        self.assertEqual(jbody(body)["status"], "PENDING")

    def test_vip_toggle_changes_billing(self):
        self.post({"action": "approve", "username": "bob"})
        self.assertFalse(self.agent.storage.user_get("bob")["is_vip"])

        status, _c, body, _x = self.post({"action": "vip", "username": "bob",
                                          "vip": True})
        self.assertEqual(status, 200)
        self.assertTrue(jbody(body)["is_vip"])
        self.assertTrue(self.agent.storage.user_get("bob")["is_vip"])

        status, _c, body, _x = self.post({"action": "vip", "username": "bob",
                                          "vip": False})
        self.assertFalse(jbody(body)["is_vip"])

    def test_inbox_rejects_bad_input(self):
        status, _c, body, _x = self.post({"action": "promote",
                                          "username": "mira"})
        self.assertEqual(status, 400)
        self.assertIn("approve|deny|unban|vip",
                      jbody(body)["error"]["message"])

        status, _c, body, _x = self.post({"action": "approve", "username": ""})
        self.assertEqual(status, 400)

        status, _c, body, _x = self.post({"action": "approve",
                                          "username": "nobody-here"})
        self.assertEqual(status, 404)

        status, _c, _b, _x = call(self.app, "DELETE", "/approve", {}, self.good)
        self.assertEqual(status, 405)

        # The gate is checked *before* the body is parsed, so a malformed
        # body from an ungated visitor is still just 401.
        status, _c, body, _x = call(self.app, "POST", "/approve", {}, {},
                                    b"{oops")
        self.assertEqual(status, 401)

        status, _c, body, _x = call(self.app, "POST", "/approve", {},
                                    self.good, b"{oops")
        self.assertEqual(status, 400)
        self.assertEqual(jbody(body)["error"]["code"], "bad_json")


